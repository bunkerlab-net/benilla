#!/usr/bin/env python3
"""Generate authored products/rays against exact pinned CMaNGOS/G3D sources.

Usage: generate_vmap_fixture.py /path/to/mangos-classic [--check]
Offline. No native parser is called; only constructed, authored geometry is queried.
"""
# SPDX-License-Identifier: GPL-3.0-or-later
import argparse
import hashlib
import pathlib
import subprocess
import sys
import tempfile

PIN = '8ec338a1704e7dcb1c0213eb7ed58f9231ade40f'
HERE = pathlib.Path(__file__).resolve().parent
VMAP = 'src/game/vmap/'
G3D = 'dep/g3dlite/'


def method(source, signature, trailer=''):
    start = source.index(signature)
    opening = source.index('{', start)
    depth, end = 1, opening + 1
    while depth:
        depth += (source[end] == '{') - (source[end] == '}')
        end += 1
    return source[start:end] + trailer + '\n'


def guarded_sources(root):
    sources = {}
    for line in (HERE / 'vmap_source_hashes.sha256').read_text().splitlines():
        expected, name = line.split('  ', 1)
        data = (root / name).read_bytes()
        if hashlib.sha256(data).hexdigest() != expected:
            raise SystemExit(f'Wrong pinned source hash: {name}; expected CMaNGOS {PIN}')
        sources[name] = data.decode('latin1')
    return sources


def source_fragments(source):
    collision = source[G3D + 'CollisionDetection.cpp']
    extracted = collision[:collision.index('#include')]
    extracted += '''#include "G3D/CollisionDetection.h"
#include "G3D/AABox.h"
namespace G3D {
Vector3 CollisionDetection::ignore;
'''
    for signature in ['float CollisionDetection::collisionTimeForMovingPointFixedAABox(',
                      'bool CollisionDetection::collisionLocationForMovingPointFixedAABox(']:
        extracted += method(collision, signature)
    extracted += '}\n'

    map_source = source[VMAP + 'MapTree.cpp']
    injected = map_source[:map_source.index('#include')]
    injected += 'namespace VMAP {\n'
    injected += method(map_source, 'class MapRayCallback', ';')
    for signature in ['StaticMapTree::StaticMapTree(', 'StaticMapTree::~StaticMapTree(',
                      'bool StaticMapTree::getIntersectionTime(']:
        injected += method(map_source, signature)
    tile = source[VMAP + 'TileAssembler.cpp']
    injected += method(tile, 'Vector3 ModelPosition::transform(')
    injected += '}\n'
    injected += '''namespace VMAP { class VMapManager2 { public:
    Vector3 convertPositionToInternalRep(float x, float y, float z) const;
};
'''
    injected += method(source[VMAP + 'VMapManager2.cpp'], 'Vector3 VMapManager2::convertPositionToInternalRep(')
    injected += '}\n'
    # The source calculateTransformedBound reads extracted assets before this block.
    # Substitute only that input acquisition with authored vertex arrays. The actual
    # ModelPosition setup, transform loop, AABox merging and position addition are
    # included byte-for-byte; no oracle intersection algorithm is reimplemented.
    bound = method(tile, 'bool TileAssembler::calculateTransformedBound(')
    setup = bound[bound.index('ModelPosition modelPosition;'):bound.index('WorldModel_Raw raw_model;')]
    loop = bound[bound.index('AABox modelBound;'):bound.rindex('}')]
    injected += '''struct AuthoredGroup { std::vector<G3D::Vector3> vertexArray; };
struct AuthoredRaw { std::vector<AuthoredGroup> groupsArray; };
static bool authoredBound(VMAP::ModelSpawn& spawn, const AuthoredRaw& raw_model) {
using namespace VMAP;
'''
    injected += setup + '\nuint32 groups = raw_model.groupsArray.size();\n'
    # The original body declares a mutable reference, so the authored input wrapper
    # is intentionally mutable too; the loop does not mutate its supplied vertices.
    injected = injected.replace('const AuthoredRaw& raw_model', 'AuthoredRaw& raw_model')
    injected += loop + '\n}\n'
    return extracted, injected


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=pathlib.Path)
    parser.add_argument('--check', action='store_true', help='Compare generated bytes without replacing fixtures')
    args = parser.parse_args()
    if sys.byteorder != 'little':
        raise SystemExit('This fixture profile requires little-endian IEEE binary32')
    root = args.source.resolve()
    source = guarded_sources(root)
    collision, methods = source_fragments(source)
    target = HERE / 'fixtures/vmap_source'
    with tempfile.TemporaryDirectory(prefix='.vmap-oracle-', dir=HERE) as temporary:
        work = pathlib.Path(temporary)
        (work / 'stubs/Platform').mkdir(parents=True)
        # Types-only substitute avoids requiring unrelated Boost/configured core.
        (work / 'stubs/Platform/Define.h').write_text('''#pragma once
#include <cstdint>
using int8=std::int8_t; using int16=std::int16_t; using int32=std::int32_t; using int64=std::int64_t;
using uint8=std::uint8_t; using uint16=std::uint16_t; using uint32=std::uint32_t; using uint64=std::uint64_t;
''')
        (work / 'collision.cpp').write_text(collision)
        (work / 'oracle.cpp').write_text((HERE / 'vmap_fixture.cpp').read_text().replace('// PINNED_SOURCE_METHODS', methods))
        sources = [root / VMAP / f'{name}.cpp' for name in ['BIH', 'WorldModel', 'ModelInstance']]
        sources += [root / G3D / f'{name}.cpp' for name in ['Ray', 'Vector3', 'AABox', 'Matrix3', 'g3dmath']]
        command = ['g++', '-std=c++17', '-O0', '-fno-fast-math', '-ffp-contract=off',
                   '-fno-strict-aliasing', '-ffunction-sections', '-fdata-sections', '-DNO_CORE_FUNCS',
                   '-I' + str(work / 'stubs'), '-I' + str(root / VMAP), '-I' + str(root / G3D),
                   str(work / 'oracle.cpp'), str(work / 'collision.cpp'), *map(str, sources),
                   '-Wl,--gc-sections', '-o', str(work / 'oracle')]
        subprocess.run(command, check=True)
        output = work / 'output'
        output.mkdir()
        subprocess.run([str(work / 'oracle'), str(output)], check=True)
        bih_command = command.copy()
        bih_command[bih_command.index(str(work / 'oracle.cpp'))] = str(HERE / 'vmap_bih_fixture.cpp')
        bih_command[-1] = str(work / 'bih-oracle')
        subprocess.run(bih_command, check=True)
        (output / 'bih-oracle.tsv').write_bytes(subprocess.check_output([str(work / 'bih-oracle')]))
        products = sorted(output.iterdir())
        if args.check:
            for product in products:
                if not (target / product.name).is_file() or product.read_bytes() != (target / product.name).read_bytes():
                    raise SystemExit(f'Fixture differs: {product.name}')
        else:
            target.mkdir(parents=True, exist_ok=True)
            for product in products:
                (target / product.name).write_bytes(product.read_bytes())
        print(f'{"Verified" if args.check else "Generated"} {len(products)} authored VMap oracle files in {target}')


if __name__ == '__main__':
    main()
