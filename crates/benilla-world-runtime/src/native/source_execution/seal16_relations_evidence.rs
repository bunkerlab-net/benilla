fn digest<const N: usize>(rows: impl Iterator<Item = [u64; N]>) -> String {
    use sha2::{Digest, Sha256};
    let mut hash = Sha256::new();
    for row in rows {
        for value in row {
            hash.update(value.to_le_bytes());
        }
    }
    format!("{:x}", hash.finalize())
}
